import mysql.connector
import psycopg2

MYSQL_CONFIG = {'host': 'localhost', 'user': 'root', 'password': '1234', 'database': 'interior_db'}
PG_CONFIG = {'host': 'localhost', 'port': '5432', 'dbname': 'practice_db', 'user': 'postgres', 'password': 'admin'}

def migrate():
    try:
        my_conn = mysql.connector.connect(**MYSQL_CONFIG)
        my_cur = my_conn.cursor()
        pg_conn = psycopg2.connect(**PG_CONFIG)
        pg_cur = pg_conn.cursor()

        my_cur.execute("SHOW TABLES")
        tables = [row[0] for row in my_cur.fetchall()]
        print(f"Найдено таблиц: {len(tables)}")

        pg_cur.execute("SET session_replication_role = replica;")

        for table in tables:
            print(f"Обработка таблицы: {table}...")
            
            # Получаем структуру
            my_cur.execute(f"SHOW CREATE TABLE {table}")
            create_stmt = my_cur.fetchone()[1]
            
            # Чистим и адаптируем синтаксис под PostgreSQL
            create_stmt = create_stmt.replace('`', '"')
            create_stmt = create_stmt.replace('int(11)', 'INTEGER')
            create_stmt = create_stmt.replace('int', 'INTEGER')
            create_stmt = create_stmt.replace('varchar', 'VARCHAR')
            create_stmt = create_stmt.replace('text', 'TEXT')
            create_stmt = create_stmt.replace('datetime', 'TIMESTAMP')
            create_stmt = create_stmt.replace('AUTO_INCREMENT', 'GENERATED BY DEFAULT AS IDENTITY')
            create_stmt = create_stmt.replace('UNSIGNED', '')
            # Убираем лишнее из MySQL
            if 'ENGINE=' in create_stmt:
                create_stmt = create_stmt.split('ENGINE=')[0]
            
            pg_cur.execute(f"DROP TABLE IF EXISTS {table} CASCADE")
            try:
                pg_cur.execute(create_stmt)
            except Exception as e:
                print(f"  Ошибка создания {table}: {e}")
                pg_conn.rollback()
                continue

            # Копируем данные
            my_cur.execute(f"SELECT * FROM {table}")
            rows = my_cur.fetchall()
            
            if rows:
                placeholders = ', '.join(['%s'] * len(rows[0]))
                insert_query = f"INSERT INTO {table} VALUES ({placeholders})"
                try:
                    pg_cur.executemany(insert_query, rows)
                    print(f"  Перенесено: {len(rows)}")
                except Exception as e:
                    print(f"  Ошибка данных {table}: {e}")
                    pg_conn.rollback()
            pg_conn.commit()

        pg_cur.execute("SET session_replication_role = DEFAULT;")
        pg_conn.commit()
        print("🎉 Перенос завершен!")

    except Exception as e:
        print(f"Критическая ошибка: {e}")
    finally:
        if 'my_cur' in locals(): my_cur.close()
        if 'my_conn' in locals(): my_conn.close()
        if 'pg_cur' in locals(): pg_cur.close()
        if 'pg_conn' in locals(): pg_conn.close()

if __name__ == "__main__":
    migrate()